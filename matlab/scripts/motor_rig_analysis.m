function A = motor_rig_analysis(days, outDay)
%MOTOR_RIG_ANALYSIS  Every rig run of some days against the identified model, in depth.
%
%   A = motor_rig_analysis({'2026-10-23', '2026-10-24'}, '2026-10-24')
%
%   For every FINISHED run of a course hardware experiment on those days: the run's own
%   settings are simulated on the identified rig model (servolab.motor.identifiedSim with
%   rigModel, as in the app), both are scored with servolab.motor.stepMetrics, and then
%     - model accuracy: RMSE and metric errors per run, per loop and controller
%     - repeatability: spread of each metric over repeats of the same run
%     - firmware: start transients and the reverse-runaway stops, per firmware revision
%     - a refit of the model on the day's open-loop steps (servolab.motor.fitIdentified)
%     - Simulink: servo_identified.slx against identifiedSim on the same runs
%   Writes results/reports/dc_motor/<outDay>/ANALYSIS.md, analysis_runs.csv and a_*.png.
%   Every number comes from data/raw; the model was fitted on 2026-10-11 data only.

    if nargin < 1, days = {'2026-10-23', '2026-10-24'}; end
    if nargin < 2, outDay = days{end}; end
    root = servolab.repoRoot();
    out = fullfile(root, 'results', 'reports', 'dc_motor', outDay);
    if ~isfolder(out), mkdir(out); end
    model = servolab.motor.rigModel(); P = servolab.motor.params();
    E = servolab.motor.hwExperiments();
    Rg = servolab.data.register(); Rg = Rg(strcmp(Rg.apparatus, 'MOTOR'), :);
    I = servolab.motor.runIndex();
    dayOf = cellstr(string(I.created, 'yyyy-MM-dd'));
    I = I(ismember(dayOf, days), :);
    I = sortrows(I, 'created');
    fwOf = containers.Map(Rg.run_id, Rg.firmware);
    L = {};

    % ------------------------------------------------------------ every run, rig vs model
    rows = {};
    traces = struct('id', {}, 'T', {}, 'S', {});
    for k = 1:height(I)
        r = table2struct(I(k, :));
        j = find(strcmp({E.name}, r.name), 1);
        R = servolab.motor.loadHardwareRun(r.id); T = R.T;
        fw = ''; if isKey(fwOf, r.id), fw = fwOf(r.id); end
        first = NaN; if height(T) > 0, first = T.meas(1); end
        startCmd = NaN; if height(T) > 0, startCmd = T.u(1); end
        if isempty(j) || height(T) < 5
            rows(end + 1, :) = {r.id, dayStr(r.created), fw, r.name, r.run, r.loop, r.fb, r.ctrl, r.Kp, r.Ki, ...
                r.result, first, startCmd, NaN, NaN, NaN, NaN, NaN, NaN, NaN, NaN}; %#ok<AGROW>
            continue
        end
        c = R.cfg; c.Kd = 0; if ~isfield(c, 'spdFb'), c.spdFb = 'drive'; end
        c.latency = servolab.motor.defaultConfig('rig', c.loop).latency;   % today's measured value, not the one stored with the run
        run = r.run; if isnan(run), run = 1; end
        prof = E(j).runs(run).profile;
        S = servolab.motor.identifiedSim(model, c, prof, T.t_s(end));
        if strcmp(c.loop, 'speed'), S.y = S.w; else, S.y = S.thOut; end
        res = resolution(c);
        mr = servolab.motor.stepMetrics(T.t_s, T.setpoint, T.meas, T.u, 'Resolution', res, 'uMax', c.uMax);
        ms = servolab.motor.stepMetrics(S.tk, S.r, S.meas, S.u, 'Resolution', res, 'uMax', c.uMax);
        e = NaN;
        if strcmp(r.result, 'FINISHED')
            ys = interp1(S.tk, S.meas, T.t_s, 'nearest', NaN); ok = isfinite(ys);      % rig times jitter by ms
            e = sqrt(mean((ys(ok) - T.meas(ok)).^2));
            traces(end + 1) = struct('id', r.id, 'T', T, 'S', S); %#ok<AGROW>
        end
        rows(end + 1, :) = {r.id, dayStr(r.created), fw, r.name, run, r.loop, r.fb, r.ctrl, r.Kp, r.Ki, ...
            r.result, first, startCmd, e, mr.rise, ms.rise, mr.overshoot, ms.overshoot, mr.ess, ms.ess, ...
            max(abs(T.setpoint))}; %#ok<AGROW>
    end
    A = cell2table(rows, 'VariableNames', {'run_id', 'day', 'firmware', 'experiment', 'run', 'loop', 'fb', ...
        'ctrl', 'Kp', 'Ki', 'result', 'first_meas', 'first_cmd', 'rmse', 'rise_rig', 'rise_model', ...
        'over_rig', 'over_model', 'ess_rig', 'ess_model', 'sp_max'});
    writetable(A, fullfile(out, 'analysis_runs.csv'));
    fin = A(strcmp(A.result, 'FINISHED') & isfinite(A.rmse), :);
    fin.fb(cellfun(@isempty, fin.fb)) = {'-'};                % findgroups drops empty groups

    say('# DC motor: rig against model, %s', strjoin(days, ' and '));
    say('');
    say(['Generated by `matlab/scripts/motor_rig_analysis.m` from `data/raw/dc_motor`: %d runs, %d finished ' ...
         'course runs scored. Grey (model) is `identifiedSim` with `rigModel` (fitted on 2026-10-11 only) running ' ...
         'each run''s own settings and profile, so every comparison is a prediction. Per-run numbers: ' ...
         '[`analysis_runs.csv`](analysis_runs.csv).'], height(A), height(fin));
    say('');

    % ------------------------------------------------------------ runaway stops, from the session logs
    say('## 1. Reverse runaway at run start (OI-M12) and the firmware fix');
    Z = logStarts(fullfile(root, 'results', 'evidence', 'logs'));
    writetable(Z, fullfile(out, 'analysis_run_starts.csv'));
    say(['Counted from every session log (`results/evidence/logs/hw_session_*.log`), which also holds the runs the ' ...
         'app did not save. A start is **at risk** when it is a speed run (drive or encoder feedback) that follows a run ' ...
         'which ended with the motor at rest under a 0 command, with no HOME sent in between. Firmware `e60d046` and later ' ...
         'write HOME at every RUN itself; `f87b283` also waits 150 ms after it before enabling the drive.']);
    say('');
    say('| firmware | sessions | runs | at-risk starts | runaway stops at those | other runaway stops | first sample at risk (rpm, median) | jerk at risk (counts, median) |');
    say('|---|---:|---:|---:|---:|---:|---:|---:|');
    for f = unique(Z.firmware, 'stable')'
        s = Z(strcmp(Z.firmware, f{1}), :); rk = s.atRisk;
        say('| `%s` | %d | %d | %d | **%d** | %d | %s | %s |', f{1}, numel(unique(s.log)), height(s), sum(rk), ...
            sum(rk & s.runaway), sum(~rk & s.runaway), n1(median(s.first(rk & ~s.runaway), 'omitnan')), ...
            n1(median(s.jerk(rk & ~s.runaway), 'omitnan')));
    end
    old = ~Z.homeAtRun; new = Z.homeAtRun;
    say('');
    say(['Before the fix: **%d of %d** at-risk starts ran away. After it: **%d of %d**. Every runaway ran the motor ' ...
         'backwards at full voltage within 0.1 s (the drive''s 53 rpm/s ramp was bypassed), and the guard cut motor ' ...
         'power within 0.2 s every time. The cause inside the drive is UNVERIFIED; the fix rests on this record.'], ...
         sum(old & Z.atRisk & Z.runaway), sum(old & Z.atRisk), sum(new & Z.atRisk & Z.runaway), sum(new & Z.atRisk));
    say('');
    say(['What remains at enable: the first sample reads tens of rpm backwards, mostly because the HOME resets the ' ...
         'count the speed is computed from; the encoder shows a real jerk (largest count excursion in the first 0.5 s, ' ...
         'last column; 1 count = 0.069 deg). It never came near the guard''s limits.']);
    say('');
    plotStarts(Z);
    say('![start transients](a_start_transients.png)');
    say('');

    % ------------------------------------------------------------ physics: free speed
    say('## 2. The datasheet physics against the runaways');
    [~, Dp] = servolab.motor.physics();
    ra = Z(Z.runaway & Z.peak3 > 100, :);
    say(['Each runaway is, by accident, a full-voltage test: the drive applied the whole supply to the motor (the 2026-10-11 ' ...
         'ones came from the reversed encoder wiring, positive feedback, the later ones from OI-M12). Largest speed read in ' ...
         'the first 0.3 s of those %d runs: median **%.1f rpm**, range %.1f to %.1f (the drive register reads in 4.6 rpm ' ...
         'steps). The datasheet model (`servolab.motor.physics`: 180 rpm at 12 V, 0.8 A no-load, 7.5 A stall, 11.2 V ' ...
         'battery) predicts **%.1f rpm** free speed at the output shaft, %+.1f %% from the median. The battery voltage ' ...
         'was not logged, so this agreement is within the voltage uncertainty, not a proof.'], height(ra), ...
         median(ra.peak3), min(ra.peak3), max(ra.peak3), Dp.w_free_out, 100 * (Dp.w_free_out / median(ra.peak3) - 1));
    say('');

    % ------------------------------------------------------------ model accuracy
    say('## 3. How well the model predicts the rig');
    say('RMSE between the rig''s measurement and the model''s measurement at the same controller instants, over the whole run.');
    say('');
    say('| loop | controller | runs | RMSE median | RMSE max | rise rig / model (s, median) | overshoot rig / model (%%, median) |');
    say('|---|---|---:|---:|---:|---:|---:|');
    G = findgroups(fin.loop, fin.fb, fin.ctrl);
    for g = 1:max(G)
        s = fin(G == g, :);
        u = ternary(strcmp(s.loop{1}, 'speed'), 'rpm', 'deg');
        say('| %s%s | %s | %d | %.2f %s | %.2f %s | %s / %s | %s / %s |', s.loop{1}, fbTag(s.fb{1}), s.ctrl{1}, height(s), ...
            median(s.rmse), u, max(s.rmse), u, n2(median(s.rise_rig, 'omitnan')), n2(median(s.rise_model, 'omitnan')), ...
            n1(median(s.over_rig, 'omitnan')), n1(median(s.over_model, 'omitnan')));
    end
    say('');
    rel = fin.rmse ./ max(abs(fin.sp_max), 1);
    [~, w] = max(rel);
    say(['Relative to the largest setpoint of each run, the median RMSE is **%.1f %%** (worst %.1f %%, `%s`). Part of ' ...
         'every speed RMSE is quantisation: the drive register moves in 4.6 rpm steps and encoder speed in 0.115 rpm ' ...
         'steps at Ts 0.1 s. The same quantisation makes the open-loop "overshoot" of 7.5 %% on the register: one ' ...
         'step above 60 rpm.'], 100 * median(rel, 'omitnan'), 100 * rel(w), shortId(fin.run_id{w}));
    say('');
    plotAccuracy(fin);
    say('![model accuracy](a_model_accuracy.png)');
    say('');

    % ------------------------------------------------------------ repeatability
    say('## 4. Repeatability: the same run, again and again');
    say(['Each row: one run of one experiment repeated across the sessions (FINISHED runs only). The static map (S3-3) ' ...
         'is in the session report; its "overshoot" between 1 rpm stairs means nothing.']);
    say('');
    say('| experiment | run | n | rise (s) mean ± sd | overshoot (%%) mean ± sd | e_ss mean ± sd | RMSE vs model mean |');
    say('|---|---:|---:|---:|---:|---:|---:|');
    [G, keyE, keyR] = findgroups(fin.experiment, fin.run);
    for g = 1:max(G)
        s = fin(G == g, :);
        if height(s) < 2 || startsWith(shortName(keyE{g}), 'S3-3'), continue; end
        say('| %s | %d | %d | %s ± %s | %s ± %s | %s ± %s | %.2f |', shortName(keyE{g}), keyR(g), height(s), ...
            n2(mean(s.rise_rig, 'omitnan')), n2(std(s.rise_rig, 'omitnan')), n1(mean(s.over_rig, 'omitnan')), ...
            n1(std(s.over_rig, 'omitnan')), n2(mean(s.ess_rig, 'omitnan')), n2(std(s.ess_rig, 'omitnan')), mean(s.rmse));
    end
    say('');
    plotRepeat(traces, A);
    say('![repeatability](a_repeatability.png)');
    say('');

    % ------------------------------------------------------------ refit
    say('## 5. Refit of the model on this session''s open-loop steps');
    ol = fin(strcmp(fin.ctrl, 'OL') & strcmp(fin.loop, 'speed') & strcmp(fin.day, outDay) & contains(fin.experiment, 'S3-2/S3-4'), :);
    if height(ol) >= 2
        [mf, info] = servolab.motor.fitIdentified(ol.run_id');
        say('Fitted on %d open-loop steps of %s (both feedback paths):', height(ol), outDay);
        say('');
        say('| parameter | rigModel (2026-10-11) | refit (%s) |', outDay);
        say('|---|---:|---:|');
        say('| gain K | %.3f | %.3f |', model.K, mf.K);
        say('| ramp (output rpm/s) | %.1f | %.1f |', model.acc, mf.acc);
        say('| tau (s) | %.3f | %.3f |', model.tau, mf.tau);
        say('| dead time (s) | %.3f | %.3f |', model.theta, mf.theta);
        say('| fit RMSE (rpm) | 2.34 | %.2f |', info.rmse);
        say('');
        say('The rig has not drifted in 13 days if the refit stays within the run-to-run spread of section 3.');
        A.Properties.UserData.refit = mf;
    else
        say('Not enough finished open-loop steps on %s.', outDay);
    end
    say('');

    % ------------------------------------------------------------ Simulink
    say('## 6. Simulink against the MATLAB model');
    if ~isempty(ver('simulink')) && license('test', 'Simulink')
        addpath(fullfile(root, 'matlab', 'models', 'dc_motor'));
        say('`servo_identified.slx` run with the same settings as `identifiedSim`, one run of each kind:');
        say('');
        say('| run | loop | controller | max difference Simulink - MATLAB | RMSE Simulink vs rig | RMSE MATLAB vs rig |');
        say('|---|---|---|---:|---:|---:|');
        picks = pickKinds(fin);
        for p = picks'
            r = fin(p, :); R = servolab.motor.loadHardwareRun(r.run_id{1}); T = R.T;
            c = R.cfg; c.Kd = 0; if ~isfield(c, 'spdFb'), c.spdFb = 'drive'; end
        c.latency = servolab.motor.defaultConfig('rig', c.loop).latency;   % today's measured value, not the one stored with the run
            j = find(strcmp({E.name}, r.experiment{1}), 1); prof = E(j).runs(r.run).profile;
            S = servolab.motor.identifiedSim(model, c, prof, T.t_s(end));
            K = run_motor_identified_simulink(model, c, prof, T.t_s(end));
            n = min(numel(K.tk), numel(S.tk));
            assert(max(abs(K.tk(1:n) - S.tk(1:n))) < 1e-6, 'servolab:analysis:grid', 'Simulink and MATLAB sample at different instants');
            d = max(abs(K.measK(1:n) - S.meas(1:n)));
            ys = interp1(K.tk, K.measK, T.t_s, 'nearest', NaN); ok2 = isfinite(ys);
            say('| `%s` | %s%s | %s | %.3f | %.2f | %.2f |', shortId(r.run_id{1}), r.loop{1}, fbTag(r.fb{1}), r.ctrl{1}, d, ...
                sqrt(mean((ys(ok2) - T.meas(ok2)).^2)), r.rmse);
        end
        say('');
        say(['Compared at the controller samples. The two implementations of the same model (`identifiedSim` in MATLAB, ' ...
             'the .slx in Simulink) give the listed difference; their RMSE against the rig differs only where the rig''s ' ...
             'samples fall between the model''s.']);
    else
        say('Simulink is not installed here: section skipped.');
    end
    say('');

    writelines(string(L), fullfile(out, 'ANALYSIS.md'));
    fprintf('analysis -> %s\n', fullfile(out, 'ANALYSIS.md'));

    % ============================================================== helpers
    function say(fmt, varargin), s = sprintf(fmt, varargin{:}); L = [L, strsplit(s, newline)]; end
    function v = resolution(c)
        if strcmp(c.loop, 'position'), v = 2 * P.deg_per_count;
        elseif strcmp(c.spdFb, 'encoder'), v = 60 / (5200 * c.Ts);
        else, v = P.spd_fb_step_base_rpm / P.N; end
    end
    function plotStarts(Z)
        f = fig(1000, 440); ax = axes(f); hold(ax, 'on'); grid(ax, 'on');
        fws = unique(Z.firmware, 'stable'); col = lines(numel(fws));
        for q = 1:numel(fws)
            s = Z(strcmp(Z.firmware, fws{q}) & Z.speedRun, :);
            x = q + 0.3 * (rand(height(s), 1) - 0.5);
            v = s.first - s.firstCmd;
            scatter(ax, x(~s.atRisk), v(~s.atRisk), 24, col(q, :), 'o', 'HandleVisibility', 'off');
            scatter(ax, x(s.atRisk & ~s.runaway), v(s.atRisk & ~s.runaway), 46, col(q, :), 'filled', 'HandleVisibility', 'off');
            scatter(ax, x(s.runaway), v(s.runaway), 70, [0.85 0.1 0.1], 'x', 'LineWidth', 2, 'HandleVisibility', 'off');
        end
        h = [scatter(ax, NaN, NaN, 24, 'k', 'o'), scatter(ax, NaN, NaN, 46, 'k', 'filled'), scatter(ax, NaN, NaN, 70, [0.85 0.1 0.1], 'x', 'LineWidth', 2)];
        legend(ax, h, {'other starts', 'at-risk starts (after rest, no HOME)', 'runaway: motor power cut'}, 'Location', 'southwest');
        set(ax, 'XTick', 1:numel(fws), 'XTickLabel', fws, 'XLim', [0.5 numel(fws) + 0.5], 'TickLabelInterpreter', 'none');
        ylabel(ax, 'first sample minus command (rpm)');
        title(ax, 'Speed runs: the first sample after RUN, per firmware revision (all sessions)');
        save_(f, 'a_start_transients.png');
    end
    function plotAccuracy(fin)
        f = fig(1000, 440); tl = tiledlayout(f, 1, 2, 'TileSpacing', 'compact');
        a = nexttile(tl); hold(a, 'on'); grid(a, 'on');
        sp = strcmp(fin.loop, 'speed');
        ok = isfinite(fin.over_rig) & isfinite(fin.over_model) & ~strcmp(fin.ctrl, 'OL');   % open loop: quantisation on small stairs
        scatter(a, fin.over_model(ok & sp), fin.over_rig(ok & sp), 36, [0 0.45 0.74], 'filled', 'DisplayName', 'speed');
        scatter(a, fin.over_model(ok & ~sp), fin.over_rig(ok & ~sp), 36, [0.85 0.33 0.1], 'filled', 'DisplayName', 'position');
        mx = max([fin.over_rig(ok); fin.over_model(ok); 10]); plot(a, [0 mx], [0 mx], 'k--', 'HandleVisibility', 'off');
        xlabel(a, 'overshoot, model (%)'); ylabel(a, 'overshoot, rig (%)'); legend(a, 'Location', 'northwest'); title(a, 'Overshoot (closed loop)');
        b = nexttile(tl); hold(b, 'on'); grid(b, 'on');
        ok = isfinite(fin.rise_rig) & isfinite(fin.rise_model);
        scatter(b, fin.rise_model(ok & sp), fin.rise_rig(ok & sp), 36, [0 0.45 0.74], 'filled');
        scatter(b, fin.rise_model(ok & ~sp), fin.rise_rig(ok & ~sp), 36, [0.85 0.33 0.1], 'filled');
        mx = max([fin.rise_rig(ok); fin.rise_model(ok); 1]); plot(b, [0 mx], [0 mx], 'k--');
        xlabel(b, 'rise time, model (s)'); ylabel(b, 'rise time, rig (s)'); title(b, 'Rise time (10-90 %)');
        title(tl, 'Every finished course run: rig against the identified model''s prediction');
        save_(f, 'a_model_accuracy.png');
    end
    function plotRepeat(traces, A)
        f = fig(1000, 460); ax = axes(f); hold(ax, 'on'); grid(ax, 'on');
        want = A.run_id(contains(A.experiment, 'S3-2/S3-4') & A.run == 1 & strcmp(A.result, 'FINISHED'));
        n = 0;
        for q = 1:numel(traces)
            if ~any(strcmp(want, traces(q).id)), continue; end
            n = n + 1;
            if n == 1, plot(ax, traces(q).S.tk, traces(q).S.meas, '-', 'Color', [0.55 0.55 0.55], 'LineWidth', 3, 'DisplayName', 'model'); end
            plot(ax, traces(q).T.t_s, traces(q).T.meas, '-', 'Color', [0 0.45 0.74 0.35], 'LineWidth', 1.2, 'HandleVisibility', ternary(n == 1, 'on', 'off'), 'DisplayName', 'rig runs');
        end
        xlabel(ax, 't (s)'); ylabel(ax, 'speed (rpm), drive register');
        title(ax, sprintf('S3-2/S3-4 open-loop step 0 -> 60 rpm: %d rig runs over two sessions, and the model', n));
        legend(ax, 'Location', 'northeast');
        save_(f, 'a_repeatability.png');
    end
    function f = fig(w, h)
        f = figure('Visible', 'off', 'Position', [100 100 w h], 'Color', 'w');
        try, theme(f, 'light'); catch, end
    end
    function save_(f, name), exportgraphics(f, fullfile(out, name), 'Resolution', 130); close(f); end
end

function Z = logStarts(logDir)
    % every RUN in every session log: firmware, loop, what came before it, how it started
    d = dir(fullfile(logDir, 'hw_session_*.log'));
    rows = {};
    for k = 1:numel(d)
        txt = splitlines(fileread(fullfile(d(k).folder, d(k).name)));
        fw = '?'; loop = ''; between = {}; prevEnd = []; cur = []; runs = {};
        for i = 1:numel(txt)
            tok = regexp(txt{i}, '^\s*([\d.]+) ([<>]) \$([^*]*)', 'tokens', 'once');
            if isempty(tok), continue; end
            f = strsplit(tok{3}, ',');
            if tok{2} == '<'
                if strcmp(f{1}, 'HELLO') && numel(f) >= 4, fw = f{4}; end
                if strcmp(f{1}, 'TEL') && ~isempty(cur) && numel(f) >= 13
                    cur.tel(end + 1, :) = str2double(f([8 10 11])); %#ok<AGROW>   meas, u, counts
                end
                if strcmp(f{1}, 'ERR') && ~isempty(cur) && numel(f) >= 5 && contains(f{5}, 'runaway'), cur.runaway = true; end
            else
                switch f{1}
                    case 'CFG', if numel(f) >= 3, loop = f{3}; end
                    case {'STOP', 'HOME', 'ESTOP'}, between{end + 1} = f{1}; %#ok<AGROW>
                    case 'RUN'
                        if ~isempty(cur), runs{end + 1} = cur; prevEnd = cur; end %#ok<AGROW>
                        cur = struct('fw', fw, 'loop', loop, 'home', any(strcmp(between, 'HOME')), 'tel', zeros(0, 3), ...
                            'runaway', false, 'prev', prevEnd, 't', str2double(tok{1}));
                        between = {};
                end
            end
        end
        if ~isempty(cur), runs{end + 1} = cur; end %#ok<AGROW>
        for j = 1:numel(runs)
            r = runs{j};
            if isempty(r.tel), continue; end
            atRest = false;
            if j > 1 && ~isempty(runs{j - 1}.tel) && ~runs{j - 1}.runaway && ~strcmp(runs{j - 1}.loop, 'P')
                e = runs{j - 1}.tel(end, :);
                atRest = abs(e(2)) < 0.2 && abs(e(1)) < 0.5;
            end
            speedRun = any(strcmp(r.loop, {'S', 'E'}));
            fwName = regexprep(r.fw, '^rhino_servo_lab ', '');
            % firmware that writes HOME at every RUN (OI-M12 fix): add later revisions here
            homeAtRun = any(startsWith(fwName, {'e60d046', 'f87b283'}));
            % jerk: count excursion in the first 0.5 s, only while 0 is commanded (real motion otherwise)
            n5 = min(5, size(r.tel, 1)); c = r.tel(1:n5, 3); jerk = NaN;
            if strcmp(r.loop, 'E') && all(isfinite(c)) && all(r.tel(1:n5, 2) == 0), jerk = max(c) - min(c); end
            rows(end + 1, :) = {d(k).name, fwName, r.t, r.loop, speedRun, atRest && speedRun && ~r.home, r.home, homeAtRun, ...
                r.runaway, r.tel(1, 1), r.tel(1, 2), jerk, max(abs(r.tel(1:min(3, end), 1)))}; %#ok<AGROW>
        end
    end
    Z = cell2table(rows, 'VariableNames', {'log', 'firmware', 't_log_s', 'loop', 'speedRun', 'atRisk', 'homeSent', ...
        'homeAtRun', 'runaway', 'first', 'firstCmd', 'jerk', 'peak3'});
end

function s = dayStr(t), s = char(string(t, 'yyyy-MM-dd')); end
function s = fbTag(fb), if isempty(fb) || strcmp(fb, '-'), s = ''; else, s = [' (' fb ')']; end, end
function s = n1(v), if isnan(v), s = '-'; else, s = sprintf('%.1f', v); end, end
function s = n2(v), if isnan(v), s = '-'; else, s = sprintf('%.2f', v); end, end
function s = ternary(c, a, b), if c, s = a; else, s = b; end, end
function s = shortId(id), s = regexprep(id, '_\d{8}-\d{6}', ''); end
function s = shortName(n), s = regexprep(regexprep(n, '^Course ', ''), ':.*$', ''); end
function p = pickKinds(fin)
    [G] = findgroups(fin.loop, fin.fb, fin.ctrl);
    p = zeros(max(G), 1);
    for g = 1:max(G), j = find(G == g); p(g) = j(end); end
end
