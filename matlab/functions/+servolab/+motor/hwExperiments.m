function E = hwExperiments()
%HWEXPERIMENTS  Hardware experiment library for the lab rig (RMCS-2303 + RMCS-5032).
%
%   E = servolab.motor.hwExperiments()
%
%   Each experiment is one or more runs. A run fixes the loop, controller and gains,
%   then plays a setpoint profile [t_s, setpoint] (output rpm for 'speed', output
%   degrees for 'position', measured from where the run starts) for 'duration' s.
%   ExperimentRunner plays them on the hardware; every run is saved as raw data.
%
%   Gains are tuned in simulation against the lab drive's MEASURED acceleration register
%   (5000, ramp ~50 output rpm/s): faster integral gains overshoot ~40 % because the
%   integrator winds up while the drive ramps.
%   Limits: |speed| <= 120 rpm in control experiments and <= 150 rpm in the static map (the
%   motor's free speed on the 11.1 V battery is ~166 rpm), position moves <= 1 revolution.
%
%   Optional per-run settings (name-value after the duration): 'spdFb' 'drive'|'encoder'
%   (speed feedback, see the firmware header), 'uMax' (command limit, output rpm).
%   E(k).key is stable; E(k).name is what the app shows; E(k).aliases are earlier names that
%   recorded runs may carry (servolab.motor.experimentKey maps any of them to the key).

    E = struct('key', {}, 'name', {}, 'aliases', {}, 'id', {}, 'purpose', {}, 'runs', {});
    sp = @(ctrl, Kp, Ki, prof, dur, varargin) run('speed', ctrl, Kp, Ki, prof, dur, varargin{:});
    ps = @(ctrl, Kp, Ki, prof, dur, varargin) run('position', ctrl, Kp, Ki, prof, dur, varargin{:});
    enc = {'spdFb', 'encoder'};
    stair = [0 0; 2 1; 5 2; 8 3; 11 5; 14 8; 17 12; 20 20; 23 40; 26 60; 29 90; 32 120; 35 150; 38 0];

    add('ol_speed_steps', 'Open-loop speed steps, 20 to 120 rpm', {'Speed steps, open loop (drive only)'}, 'MOTOR-02', ...
        'Identify the drive + motor: ramp rate, settling, steady speed at 20...120 rpm.', ...
        sp('OL', 0, 0, [0 20; 3 40; 6 80; 9 120; 12 80; 15 40; 18 0], 20));
    add('ol_reversal', 'Open-loop reversal, +30 to -30 rpm', {'Direction and reversal, open loop'}, 'MOTOR-02', ...
        'Positive command must give positive speed; reversal time through zero.', ...
        sp('OL', 0, 0, [0 30; 5 -30; 10 0], 12));
    add('speed_pi_tracking', 'Speed PI tracking setpoint changes (Kp 0.3, Ki 1.5)', {'Speed tracking, PI (Kp 0.3, Ki 1.5)'}, 'MOTOR-03', ...
        'Closed-loop speed control following setpoint changes.', ...
        sp('PI', 0.3, 1.5, [0 50; 5 100; 10 30; 15 0], 20));
    add('speed_p_sweep', 'Speed P gain sweep (Kp 0.2 / 0.5 / 0.8)', {}, 'MOTOR-05', ...
        'P alone leaves e_ss = r/(1+Kp); measure it for three gains.', ...
        [sp('P', 0.2, 0, [0 60], 8), sp('P', 0.5, 0, [0 60], 8), sp('P', 0.8, 0, [0 60], 8)]);
    add('speed_i', 'Speed I only (Ki 1.0)', {}, 'MOTOR-06', ...
        'Integral action removes the error, more slowly than PI.', ...
        sp('I', 0, 1.0, [0 60; 8 30], 16));
    add('speed_pi_step', 'Speed PI step to 60 rpm (Kp 0.3, Ki 1.5)', {'Speed PI step, 60 rpm'}, 'MOTOR-07', ...
        'PI: fast reaction and zero steady-state error.', ...
        sp('PI', 0.3, 1.5, [0 60], 10));
    add('position_p_moves', 'Position P moves: 90, -90, 360 deg (Kp 0.3)', {'Position moves, P (Kp 0.3): 90, -90, 360 deg'}, 'MOTOR-04', ...
        'Closed-loop position control; zero steady-state error expected (plant integrates).', ...
        ps('P', 0.3, 0, [0 90; 6 -90; 12 360; 20 0], 26));
    add('position_p_sweep', 'Position P gain sweep, 90 deg (Kp 0.2 / 0.3 / 0.5)', {'Position P gain sweep (Kp 0.2 / 0.3 / 0.5)'}, 'MOTOR-05', ...
        'Rise time and overshoot versus Kp for a 90 deg step.', ...
        [ps('P', 0.2, 0, [0 90], 7), ps('P', 0.3, 0, [0 90], 7), ps('P', 0.5, 0, [0 90], 7)]);
    add('position_i', 'Position I only (Ki 0.1)', {'Position I only (Ki 0.1): expect oscillation'}, 'MOTOR-06', ...
        'Two integrators in the loop: the angle oscillates around the target.', ...
        ps('I', 0, 0.1, [0 45], 12));
    add('position_pi', 'Position PI (Kp 0.3, Ki 0.03)', {}, 'MOTOR-07', ...
        'PI on position: overshoot and a slow tail, little benefit over P.', ...
        ps('PI', 0.3, 0.03, [0 90], 12));


    % --------------------------------------------- characterisation and design checks
    add('static_map', 'Static map: steady speed against command, both directions', {'Course S3-3: static map, speed vs command (fwd + rev)'}, 'MOTOR-02', ...
        'Steady speed at commands 1...150 rpm, both directions, encoder feedback: dead zone and saturation.', ...
        [sp('OL', 0, 0, stair, 41, enc{:}), sp('OL', 0, 0, [stair(:, 1), -stair(:, 2)], 41, enc{:})]);
    add('ol_step', 'Open-loop step 0 -> 60 rpm: drive register and encoder', {'Course S3-2/S3-4: open-loop step 0 -> 60 rpm (drive vs encoder speed)'}, 'MOTOR-02', ...
        'Identify K and tau; compare the drive register (~10 ms window) with encoder counts over Ts.', ...
        [sp('OL', 0, 0, [0 0; 1 60; 7 0], 10), sp('OL', 0, 0, [0 0; 1 60; 7 0], 10, enc{:})]);
    add('position_p_small', 'Position P final error on 10 deg moves (Kp 0.1 / 0.3 / 1.0)', {'Course S3-5: position P final error, 10 deg moves (Kp 0.1 / 0.3 / 1.0)'}, 'MOTOR-05', ...
        'Small moves: near the target the command is only a few rpm. Does the motor stop short?', ...
        [ps('P', 0.1, 0, [0 10], 8), ps('P', 0.3, 0, [0 10], 6), ps('P', 1.0, 0, [0 10], 6)]);
    add('speed_i_sweep', 'Speed I only, Ki sweep 0.5 / 1 / 2 / 4', {'Course S3-9: speed I only, Ki sweep 0.5 / 1 / 2 / 4'}, 'MOTOR-06', ...
        'Theory: zeta = 1 / (2 sqrt(tau K Ki)); with tau 0.72 s: 0.83 / 0.59 / 0.42 / 0.29. More Ki -> less damping.', ...
        [sp('I', 0, 0.5, [0 30], 10, enc{:}), sp('I', 0, 1, [0 30], 10, enc{:}), ...
         sp('I', 0, 2, [0 30], 10, enc{:}), sp('I', 0, 4, [0 30], 10, enc{:})]);
    add('speed_pi_design', 'Speed PI designed for zeta 0.7 on a first-order model (Kp 1.0, Ki 2.9)', {'Course S3-10: speed PI designed for zeta 0.7 (Kp 1.0, Ki 2.9)'}, 'MOTOR-07', ...
        'First-order design K 1, tau 0.72 s, wn 2 rad/s: theory 4.6 % overshoot; identified model (with latency + ramp) predicts ~29 % on the 30 -> 40 step.', ...
        sp('PI', 1.0, 2.9, [0 30; 8 40; 16 30], 22, enc{:}));
    add('windup', 'Saturation and windup: speed PI with the command limited to 50 rpm', {'Course S3-12: PI with the command limited to 50 rpm (saturation)'}, 'MOTOR-07', ...
        'Setpoint 80 rpm cannot be reached: output saturates. Clamping anti-windup lets it recover at once when the setpoint drops to 30.', ...
        sp('PI', 0.3, 1.5, [0 80; 6 30], 12, 'spdFb', 'encoder', 'uMax', 50));

    function add(key, name, aliases, id, purpose, runs)
        E(end + 1) = struct('key', key, 'name', name, 'aliases', {aliases}, 'id', id, 'purpose', purpose, 'runs', runs);
    end
end

function r = run(loop, ctrl, Kp, Ki, profile, duration, varargin)
    o = struct('spdFb', 'drive', 'uMax', NaN);
    for i = 1:2:numel(varargin), o.(varargin{i}) = varargin{i + 1}; end
    r = struct('loop', loop, 'ctrl', ctrl, 'Kp', Kp, 'Ki', Ki, 'profile', profile, 'duration', duration, ...
               'spdFb', o.spdFb, 'uMax', o.uMax);
end
