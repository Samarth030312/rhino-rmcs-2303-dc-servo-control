function M = missions()
%MISSIONS  The missions of the DC-motor mission-control app (rhino_servo_lab).
%
%   M = servolab.motor.missions()
%
%   One mission per question family of the ENR312 MOTOR handout. Each mission lists the
%   hardware experiments (servolab.motor.hwExperiments names) whose runs become its presets,
%   the numbers its table shows, and the theory value (REF) for them where there is one.
%
%   M(k).tag, .short, .brief   button text and one-sentence purpose
%   M(k).loop                  'speed' | 'position' | 'any' (LAB)
%   M(k).kind                  'step' | 'map' | 'windup' | 'physics' | 'lab'
%   M(k).experiments           cellstr of hwExperiments names (presets = their runs)
%   M(k).rows                  metric keys shown in the table (servolab.motor.stepMetrics)
%   M(k).handout               where the handout asks it

    M = struct('tag', {}, 'short', {}, 'brief', {}, 'loop', {}, 'kind', {}, ...
               'experiments', {}, 'rows', {}, 'handout', {});
    stepRows = {'rise', 'overshoot', 'settling', 'ess', 'peakU', 'rmse'};

    add('M1', 'Open loop', ...
        ['The drive closes its own speed loop; the Arduino only writes the command. A 0 -> 60 rpm step ' ...
         'shows the gain K and the drive''s acceleration ramp.'], 'speed', 'step', ...
        {'Course S3-2/S3-4: open-loop step 0 -> 60 rpm (drive vs encoder speed)', ...
         'Speed steps, open loop (drive only)', 'Direction and reversal, open loop'}, ...
        {'rise', 'ess', 'gain', 'ramp', 'rmse'}, 'S3-2, S3-4');
    add('M2', 'Static map', ...
        'Hold each command for 3 s and read the steady speed: dead zone, gain and saturation of the actuator.', ...
        'speed', 'map', {'Course S3-3: static map, speed vs command (fwd + rev)'}, ...
        {'deadzone', 'mapGain', 'wmax'}, 'S3-3');
    add('M3', 'Speed P', ...
        'P alone leaves an error e = r / (1 + K Kp). Raise Kp: the error shrinks, then the slow loop rings.', ...
        'speed', 'step', {'Speed P gain sweep (Kp 0.2 / 0.5 / 0.8)'}, ...
        [stepRows, {'essTheory'}], 'Section 1 task 4');
    add('M4', 'Speed I', ...
        'I alone removes the error. More Ki, less damping: zeta = 1 / (2 sqrt(tau K Ki)).', ...
        'speed', 'step', {'Course S3-9: speed I only, Ki sweep 0.5 / 1 / 2 / 4', 'Speed I only (Ki 1.0)'}, ...
        stepRows, 'S3-9');
    add('M5', 'Speed PI', ...
        'PI designed for zeta 0.7 at wn 2 rad/s. Compare theory, the identified model and the rig.', ...
        'speed', 'step', {'Course S3-10: speed PI designed for zeta 0.7 (Kp 1.0, Ki 2.9)', ...
         'Speed PI step, 60 rpm', 'Speed tracking, PI (Kp 0.3, Ki 1.5)'}, stepRows, 'S3-10');
    add('M6', 'Windup', ...
        ['The command is limited to 50 rpm and 80 rpm is asked. Without anti-windup the integral keeps ' ...
         'growing and the drop to 30 rpm comes late.'], 'speed', 'windup', ...
        {'Course S3-12: PI with the command limited to 50 rpm (saturation)'}, ...
        {'satTime', 'recovery', 'undershoot', 'rmse'}, 'S3-12');
    add('M7', 'Position P', ...
        'The drive turns speed into angle (an integrator), so P alone reaches the target. How close, for small moves?', ...
        'position', 'step', {'Course S3-5: position P final error, 10 deg moves (Kp 0.1 / 0.3 / 1.0)', ...
         'Position P gain sweep (Kp 0.2 / 0.3 / 0.5)', 'Position moves, P (Kp 0.3): 90, -90, 360 deg'}, ...
        {'rise', 'overshoot', 'settling', 'ess', 'peakU', 'rmse'}, 'S3-5, S3-11');
    add('M8', 'Position I', ...
        'I alone on position: two integrators in the loop. It oscillates around the target.', ...
        'position', 'step', {'Position I only (Ki 0.1): expect oscillation'}, ...
        {'overshoot', 'ess', 'peakU', 'rmse'}, 'Section 1 task 4');
    add('M9', 'Position PI', ...
        'PI on position removes a load offset, at the price of overshoot and a slow tail.', ...
        'position', 'step', {'Position PI (Kp 0.3, Ki 0.03)'}, stepRows, 'Section 1 task 4');
    add('M10', 'Armature', ...
        ['The bare motor driven by a voltage, from the datasheet: speed and current, PID, a load ' ...
         'torque, more inertia. Simulation; on the rig the drive closes this loop.'], 'any', 'physics', {}, ...
        {'rise', 'overshoot', 'settling', 'ess', 'peakU'}, '');
    add('LAB', 'Free', ...
        'Any loop, any controller, any setpoint. On the rig the setpoint changes live while it runs.', ...
        'any', 'lab', {}, stepRows, '');

    function add(tag, short, brief, loop, kind, experiments, rows, handout)
        M(end + 1) = struct('tag', tag, 'short', short, 'brief', brief, 'loop', loop, 'kind', kind, ...
                            'experiments', {experiments}, 'rows', {rows}, 'handout', handout);
    end
end
